"""The factory sounds as a C header, for the browser emulator only (app.c, __EMSCRIPTEN__): an emulated FM-1 starts
with them in its bank, as a real one does after the flasher. fm1.toml gen step: gen_factory_h.py OUT.h"""
import json
import sys
from pathlib import Path

fac = Path(__file__).resolve().parents[2] / "companion" / "factory"
man = json.loads((fac / "factory.json").read_text())["sounds"]
out = ["/* generated by app/tools/gen_factory_h.py from companion/factory: the browser emulator's factory sounds */",
       "#pragma once", "#include <stdint.h>"]
for k, s in enumerate(man):
    b = (fac / s["file"]).read_bytes()
    rows = [", ".join(str(x) for x in b[i:i + 40]) for i in range(0, len(b), 40)]
    out.append(f"static const uint8_t FAC{k}[{len(b)}] = {{\n" + ",\n".join(rows) + "};")
out.append("typedef struct { const char *name; const uint8_t *pay; uint32_t frames, rate, crc; } fac_sound_t;")
out.append("static const fac_sound_t FAC_SOUNDS[] = {" + ", ".join(
    f'{{"{s["name"]}", FAC{k}, {s["frames"]}u, {s["rate"]}u, {s["crc"]}u}}' for k, s in enumerate(man)) + "};")
out.append(f"#define FAC_N {len(man)}u")
Path(sys.argv[1]).write_text("\n".join(out) + "\n")
