"""The factory sounds as a C header (app.c): the browser emulator starts with all of them in its bank, and the FM-1
puts the starter sounds in its bank at the first start after a new install (FAC_STARTER_ONLY: only those are built
in, first in the list). fm1.toml gen step: gen_factory_h.py OUT.h"""
import json
import sys
from pathlib import Path

fac = Path(__file__).resolve().parents[2] / "companion" / "factory"
man = json.loads((fac / "factory.json").read_text())["sounds"]
man = [s for s in man if s.get("starter")] + [s for s in man if not s.get("starter")]   # the starter sounds first
ns = sum(1 for s in man if s.get("starter"))
out = ["/* generated by app/tools/gen_factory_h.py from companion/factory: the factory sounds, the starter ones first */",
       "#pragma once", "#include <stdint.h>"]
for k, s in enumerate(man):
    b = (fac / s["file"]).read_bytes()
    rows = [", ".join(str(x) for x in b[i:i + 40]) for i in range(0, len(b), 40)]
    arr = f"static const uint8_t FAC{k}[{len(b)}] = {{\n" + ",\n".join(rows) + "};"
    out.append(arr if k < ns else "#ifndef FAC_STARTER_ONLY\n" + arr + "\n#endif")
out.append("typedef struct { const char *name; const uint8_t *pay; uint32_t frames, rate, crc; } fac_sound_t;")
ent = [f'{{"{s["name"]}", FAC{k}, {s["frames"]}u, {s["rate"]}u, {s["crc"]}u}}' for k, s in enumerate(man)]
out.append("static const fac_sound_t FAC_SOUNDS[] = {" + ", ".join(ent[:ns]) + ",\n#ifndef FAC_STARTER_ONLY\n" +
           ", ".join(ent[ns:]) + "\n#endif\n};")
out.append(f"#define FAC_STARTER {ns}u")
out.append(f"#ifdef FAC_STARTER_ONLY\n#define FAC_N {ns}u\n#else\n#define FAC_N {len(man)}u\n#endif")
Path(sys.argv[1]).write_text("\n".join(out) + "\n")
