"""The companion app's "What's new" (companion/lib/changelog.js) from CHANGELOG.md, so the two never differ: every
released section ("## Next", the changes not released yet, stays out), its bullets as HTML.
  tools/gen_changelog.py [--check]     (--check: fail if the file on disk differs, for the tests and the release)"""
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "CHANGELOG.md"
OUT = ROOT / "companion/lib/changelog.js"
REPO = "https://github.com/Philip-Bos/echofield-fm1/blob/main/"


def inline(t):
    links = []

    def link(m):
        url = m.group(2) if re.match(r"https?://", m.group(2)) else REPO + m.group(2)
        links.append(f'<a href="{html.escape(url)}" target="_blank" rel="noopener">{html.escape(m.group(1))}</a>')
        return f"\x00{len(links) - 1}\x00"

    t = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", link, t)
    t = html.escape(t, quote=False)
    t = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", t)
    t = re.sub(r"`([^`]+)`", r"<code>\1</code>", t)
    return re.sub(r"\x00(\d+)\x00", lambda m: links[int(m.group(1))], t)


def sections():
    out, cur, item = [], None, None
    for line in SRC.read_text().splitlines():
        if line.startswith("## "):
            cur = {"title": line[3:].strip(), "items": []}
            out.append(cur)
            item = None
        elif cur is None:
            continue
        elif line.startswith("- "):
            item = [line[2:].strip()]
            cur["items"].append(item)
        elif line.startswith("  ") and item is not None and line.strip():
            item.append(line.strip())
        elif line.strip():
            item = [line.strip()]                # a paragraph of its own
            cur["items"].append(item)
        else:
            item = None
    return [{"title": s["title"], "items": [inline(" ".join(i)) for i in s["items"]]}
            for s in out if s["title"].lower() != "next" and s["items"]]


def main():
    text = ("// SPDX-License-Identifier: MIT\n// generated by tools/gen_changelog.py from CHANGELOG.md: do not edit\n"
            "export const CHANGES = " + json.dumps(sections(), indent=1, ensure_ascii=False) + ";\n")
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("companion/lib/changelog.js is out of date: run tools/gen_changelog.py")
        return print("changelog.js up to date")
    OUT.write_text(text)
    print(f"{OUT.relative_to(ROOT)}: {len(sections())} sections")


if __name__ == "__main__":
    main()
