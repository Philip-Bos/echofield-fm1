"""The companion app's parameter table (companion/lib/efparams.js) from the firmware's (app/params.c, app/dsp/ef_dsp.h),
so the two can never drift apart: ids, keys, labels, kinds, ranges, defaults, steps, value names, MIDI CCs, pages.

  tools/gen_efparams.py [--check]     (--check: fail if the file on disk differs, for the tests)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
H = (ROOT / "app/dsp/ef_dsp.h").read_text()
C = (ROOT / "app/params.c").read_text()
OUT = ROOT / "companion/lib/efparams.js"


def enum_list(src, first):
    body = re.search(r"enum\s*\{([^}]*\b" + first + r"\b[^}]*)\}", src, re.S).group(1)
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    return [x.strip().split("=")[0].strip() for x in body.split(",") if x.strip()]


ids = [x for x in enum_list(H, "P_POSITION") if x != "P_COUNT"]
modes = [x for x in enum_list(H, "MODE_CLOUD") if x != "MODE_COUNT"]


def strlist(name):
    m = re.search(r"static const char \*const " + name + r"\[[^\]]*\]\s*=\s*\{(.*?)\};", C, re.S)
    return re.findall(r'"([^"]*)"', m.group(1))


names = {n: strlist(n) for n in ["MODE_NAME", "MODE_BLURB", "NOTE_NAME", "SCALE_NAME", "WIN_NAME", "FILTER_NAME", "ONOFF",
                                 "KEYMODE_NAME"]}
num = r"(-?[0-9.]+)f?"
table = re.search(r"static const pinfo_t PI\[P_COUNT\]\s*=\s*\{(.*?)\n\};", C, re.S).group(1)
params = {}
for line in table.splitlines():
    line = line.strip()
    m = re.match(r"\[(P_\w+)\]\s*=\s*C\(\"(\w+)\", \"([^\"]+)\", " + ", ".join([num] * 4) + r", (\d), (\d+)\),", line)
    if m:
        pid, key, label, mn, mx, d, st, rnd, cc = m.groups()
        params[pid] = dict(key=key, label=label, kind="cont", min=float(mn), max=float(mx), def_=float(d), step=float(st),
                           rnd=rnd == "1", cc=int(cc), names=None)
        continue
    m = re.match(r"\[(P_\w+)\]\s*=\s*E\(\"(\w+)\", \"([^\"]+)\", ([\w -]+), (\d+), (\w+), (\d), (\d+)\),", line)
    if m:
        pid, key, label, mx, d, nm, rnd, cc = m.groups()
        mx = len(modes) - 1 if "MODE_COUNT" in mx else int(mx)
        params[pid] = dict(key=key, label=label, kind="enum", min=0, max=mx, def_=int(d), step=1, rnd=rnd == "1",
                           cc=int(cc), names=names[nm])
        continue
    m = re.match(r"\[(P_\w+)\]\s*=\s*B\(\"(\w+)\", \"([^\"]+)\", (\d), (\d+)\),", line)
    if m:
        pid, key, label, d, cc = m.groups()
        params[pid] = dict(key=key, label=label, kind="bool", min=0, max=1, def_=int(d), step=1, rnd=False, cc=int(cc),
                           names=names["ONOFF"])
        continue
    m = re.match(r"\[(P_\w+)\]\s*=\s*\{\"(\w+)\", \"([^\"]+)\", PK_INT, (\d), (\d+), " + ", ".join([num] * 4) + r", 0\},", line)
    if m:
        pid, key, label, rnd, cc, mn, mx, d, st = m.groups()
        params[pid] = dict(key=key, label=label, kind="int", min=float(mn), max=float(mx), def_=float(d), step=float(st),
                           rnd=rnd == "1", cc=int(cc), names=None)
        continue
    if line.startswith("["):
        sys.exit(f"gen_efparams: cannot read: {line}")
missing = [p for p in ids if p not in params]
if missing:
    sys.exit(f"gen_efparams: no table entry for {missing}")

pages = []
pt = re.search(r"static const page_t PAGES\[NPAGES\]\s*=\s*\{(.*?)\n\};", C, re.S).group(1)
for m in re.finditer(r'\{"([^"]+)", (G_\w+), \{([^}]*)\}\}', pt):
    cells = []
    for c in m.group(3).split(","):
        c = c.strip()
        cells.append(ids.index(c) if c.startswith("P_") else int(c))
    pages.append(dict(name=m.group(1), group=m.group(2)[2:].lower(), cells=cells))

out = []
for i, pid in enumerate(ids):
    p = params[pid]
    out.append({"id": i, "sym": pid, "key": p["key"], "label": p["label"], "kind": p["kind"], "min": p["min"],
                "max": p["max"], "def": p["def_"], "step": p["step"], "rnd": p["rnd"], "cc": p["cc"], "names": p["names"]})
js = ("// SPDX-License-Identifier: MIT\n// Copyright (c) 2026 Philip Bos\n"
      "// GENERATED by tools/gen_efparams.py from app/params.c and app/dsp/ef_dsp.h: do not edit.\n"
      f"export const PARAMS = {json.dumps(out, indent=1)};\n"
      f"export const PAGES = {json.dumps(pages)};\n"
      f"export const MODES = {json.dumps(names['MODE_NAME'])};\n"
      f"export const MODE_BLURB = {json.dumps(names['MODE_BLURB'])};\n"
      "export const P = Object.fromEntries(PARAMS.map((p) => [p.sym.slice(2), p.id]));\n"
      "// 16 bits on the wire (params.c pq / pdq)\n"
      "export function quant(p, v) {\n"
      "  v = Math.min(p.max, Math.max(p.min, v));\n"
      "  if (p.kind !== 'cont') return Math.round(v - p.min);\n"
      "  return Math.round(((v - p.min) / (p.max - p.min)) * 65535);\n"
      "}\n"
      "export function dequant(p, q) {\n"
      "  if (p.kind !== 'cont') return Math.min(p.max, Math.max(p.min, p.min + q));\n"
      "  return p.min + ((p.max - p.min) * q) / 65535;\n"
      "}\n")
if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text() != js:
        sys.exit("gen_efparams: companion/lib/efparams.js is out of date: run tools/gen_efparams.py")
    print("efparams.js up to date")
else:
    OUT.write_text(js)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(out)} parameters, {len(pages)} pages")
